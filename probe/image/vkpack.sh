#!/bin/sh
# 1401 Probe: the Vulkan pack, built inside the same Alpine container as the image (build.sh vkpack).
#
# The GPU test step runs Linux's own Vulkan drivers on the machine's GPUs - Mesa ANV (every Intel Xe and Arc GPU),
# RADV (every AMD GPU, Radeon RX and Ryzen iGPUs), NVK (NVIDIA) and lavapipe (the CPU, as the control) - and records
# what each one does: vulkaninfo, our gputest (compute + offscreen render, checked on the CPU), the kernel calls
# (drmlog.so) and the drivers' own command-stream dumps. That is the reference a macOS driver for that GPU reproduces.
#
# Mesa is MIT; LLVM (RADV's dependency) is Apache-2.0 with LLVM exceptions; every package's licence files travel in
# the pack under share/licenses. Like the NVIDIA packs this is NOT in the initramfs (LLVM alone is ~120 MB): it sits on
# the stick under drivers/ and is unpacked into RAM only on a machine with a GPU to test.
set -eu
say() { printf '\n== %s\n' "$*"; }
cd /work
OUT=out/vkpack; B=/tmp/vk; R=$B/root
mkdir -p "$OUT"; rm -rf "$B"; mkdir -p "$R" "$B/dl"
apk update -q
apk add -q gcc musl-dev vulkan-headers vulkan-loader-dev glslang xz coreutils >/dev/null
KEY=$( (cat probe/image/vkpack.sh probe/image/vkpack/*) | sha256sum | cut -c1-12)
MESA=$(apk policy mesa-vulkan-intel 2>/dev/null | sed -n '2s/^ *\([^:]*\):.*/\1/p')
NAME="vulkan-mesa-$MESA"
PK="$OUT/$NAME.tar.xz"
if [ -f "$PK" ] && [ "$(cat "$OUT/$NAME.stamp" 2>/dev/null)" = "$KEY" ]; then echo "$NAME: cached"; exit 0; fi
rm -f "$OUT"/vulkan-mesa-*.tar.xz "$OUT"/vulkan-mesa-*.stamp

say "Mesa $MESA Vulkan drivers and their libraries"
cd "$B/dl"
# -R: every dependency. The image already has musl and its loader; those are dropped below so the pack never shadows them.
apk fetch -q -R mesa-vulkan-intel mesa-vulkan-ati mesa-vulkan-nouveau mesa-vulkan-swrast vulkan-loader vulkan-tools
for p in *.apk; do
	case "$p" in musl-[0-9]*|busybox-*|alpine-baselayout*|python3-*|ca-certificates*) continue;; esac
	tar -xzf "$p" -C "$R" 2>/dev/null || true
done
ls -1 *.apk | sed 's/\.apk$//' | sort > "$R/PACKAGES.txt"
cd /work
rm -rf "$R/.PKGINFO" "$R"/.SIGN.* "$R"/.pre-* "$R"/.post-* "$R/usr/share/man" "$R/usr/share/doc" "$R/usr/include"
# the ICD manifests name /usr/lib/...; the pack lives under /run/vkpack, so each manifest points at its own copy
for j in "$R"/usr/share/vulkan/icd.d/*.json; do
	sed -i 's#"library_path": *"/usr/lib/#"library_path": "../../../lib/#' "$j"
done
ls "$R"/usr/share/vulkan/icd.d/

say "gputest + drmlog"
S=probe/image/vkpack
for s in compute.comp tri.vert tri.frag; do glslangValidator -V -o "$B/$s.spv" "$S/$s" >/dev/null; done
{
	echo "// generated by vkpack.sh from compute.comp, tri.vert, tri.frag (glslangValidator -V)"
	for s in compute.comp:compute_spv tri.vert:tri_vert_spv tri.frag:tri_frag_spv; do
		f=${s%%:*}; v=${s##*:}
		printf 'static const uint32_t %s[] = {' "$v"
		od -An -tx4 -v "$B/$f.spv" | tr -s ' \n' ' ' | sed 's/ *$//; s/^ //; s/ /, 0x/g; s/^/0x/'
		echo '};'
	done
} > "$B/shaders.h"
gcc -O2 -Wall -I"$B" -o "$R/usr/bin/gputest" "$S/gputest.c" -lvulkan
gcc -O2 -Wall -shared -fPIC -o "$R/usr/lib/drmlog.so" "$S/drmlog.c" -ldl
strip "$R/usr/bin/gputest" "$R/usr/lib/drmlog.so"
# the logger must record a real ioctl() (DRMLOG_ANY) and must record nothing for a non-GPU fd without it
gcc -O2 -o "$B/drmlog_check" "$S/drmlog_check.c"
rm -f "$B/pos.log" "$B/neg.log"
DRMLOG="$B/pos.log" DRMLOG_ANY=1 LD_PRELOAD="$R/usr/lib/drmlog.so" "$B/drmlog_check"
DRMLOG="$B/neg.log" LD_PRELOAD="$R/usr/lib/drmlog.so" "$B/drmlog_check"
grep -q ' ioctl 0000541b ' "$B/pos.log" || { echo "error: drmlog did not record FIONREAD"; cat "$B/pos.log" 2>/dev/null; exit 1; }
[ ! -e "$B/neg.log" ] || { echo "error: drmlog logged a non-GPU fd"; exit 1; }
echo "drmlog check: records a real ioctl ($(head -1 "$B/pos.log" | cut -c1-80)); ignores non-GPU fds"
mkdir -p "$R/usr/share/licenses/1401-gputest"; cp LICENSE "$R/usr/share/licenses/1401-gputest/" 2>/dev/null || true

say "pack"
KV=$(apk policy linux-lts 2>/dev/null | sed -n '2s/^ *\([^:]*\):.*/\1/p')
printf '{"name":"%s","mesa":"%s","drivers":["anv","radv","nvk","lavapipe"],"built_for_alpine_kernel":"%s"}\n' "$NAME" "$MESA" "$KV" > "$R/pack.json"
(cd "$R" && find . -type f ! -name SHA256SUMS | sort | xargs sha256sum > SHA256SUMS)
tar -C "$R" -cf - . | xz -6 -T0 > "$PK"
echo "$KEY" > "$OUT/$NAME.stamp"
echo "$NAME.tar.xz $(du -h "$PK" | cut -f1), $(wc -l < "$R/SHA256SUMS") files"
